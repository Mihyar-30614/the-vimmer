describe("ui.common.make_border", function()
  it("returns top/sep/bot strings of the given character width", function()
    local b = c.make_border(10)
    assert.equal(10, char_width(b.top))
    assert.equal(10, char_width(b.sep))
    assert.equal(10, char_width(b.bot))
  end)
  it("uses sharp corner characters by default", function()
    local b = c.make_border(10)
    assert.is_truthy(b.top:match("^╔"))
    assert.is_truthy(b.top:match("╗$"))
    assert.is_truthy(b.sep:match("^╠"))
    assert.is_truthy(b.sep:match("╣$"))
    assert.is_truthy(b.bot:match("^╚"))
    assert.is_truthy(b.bot:match("╝$"))
  end)
  it("supports rounded corners when requested", function()
    local b = c.make_border(10, "rounded")
    assert.is_truthy(b.top:match("^╭"))
    assert.is_truthy(b.top:match("╮$"))
    assert.is_truthy(b.sep:match("^├"))
    assert.is_truthy(b.sep:match("┤$"))
    assert.is_truthy(b.bot:match("^╰"))
    assert.is_truthy(b.bot:match("╯$"))
    local narrow = c.make_border(8, "rounded")
    assert.equal("│hi    │", narrow.row("hi"))
  end)
  it("reads border style from plugin config", function()
    package.loaded["the-vimmer"] = { config = { border = "rounded" } }
    assert.equal("rounded", c.current_border_style())
    assert.is_truthy(c.make_border(12).top:match("^╭"))
    package.loaded["the-vimmer"] = nil
  end)
  it("returns a row function that pads through pad_row", function()
    local b = c.make_border(8)
    assert.equal("║hi    ║", b.row("hi"))
  end)
end)

