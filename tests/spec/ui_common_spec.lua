local c = require("the-vimmer.ui.common")

local function char_width(s)
  return #(s:gsub("[\194-\223][\128-\191]", "_")
            :gsub("[\224-\239][\128-\191][\128-\191]", "_")
            :gsub("[\240-\247][\128-\191][\128-\191][\128-\191]", "_"))
end

describe("ui.common.format_key", function()
